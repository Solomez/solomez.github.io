const MEDIUM_RU = { water: 'вода', fat: 'масло', dry: 'сухая сковорода', milk: 'молоко', sauce: 'соус' };
// среда шага: по общему действию или способу продукта («pasta:boil_drain:boil» → варка в воде) и этапу
const WATER_WAYS = new Set(['boil', 'mash', 'steep', 'boil_drain', 'absorb', 'brew', 'oven_dish', 'in_dish', 'poach', 'blanch']);
const SAUCE_WAYS = new Set(['braise', 'simmer', 'sauce', 'in_sauce', 'heat_in_sauce', 'sauce_finish', 'melt_lid', 'stew']);
export function heatMedium(step) {
  if (!step || step.oven || step.vessel === 'kettle') return null;
  const o = String(step.origin || '');
  const liquid = String(step.ctx?.liquid || '');
  const parts = o.split(':');
  const way = parts[0] === 'act' ? parts[1] : parts.length >= 3 ? parts[1] : parts[0];
  const stage = String(step.id || parts[2] || '');
  if (way === 'warm_milk' || /^milk/.test(liquid)) return 'milk';
  if (['boil_water', 'bring_to_boil', 'heat_water'].includes(way)) return 'water';
  if (['simmer_sauce', 'reduce', 'warm_through', 'deglaze', 'toss_in_sauce'].includes(way)) return 'sauce';
  if (way === 'toast_bread' || (way === 'toast' && stage === 'toast' && !liquid)) return 'dry';
  // обжарка внутри «тушения» или «соуса» — в масле
  if (/^(brown|sear|fry|saute|toast|prefry|crisp|side)/.test(stage)) return 'fat';
  if (SAUCE_WAYS.has(way)) return 'sauce';
  if (WATER_WAYS.has(way)) return 'water';
  return 'fat';
}
export function heatTerms(step, text = '', stove = 'electric') {
  if (!step?.heat || step.oven || step.vessel === 'kettle') return [];
  const med = heatMedium(step) || 'fat';
  const t = ` ${String(text).toLowerCase().replace(/ё/g, 'е')} `.replace(/[.,;:!?)]/g, ' ');
  // уровень плашки шага и уровни, до которых текст велит прибавить или убавить
  const levels = HEAT_LEVELS.filter((l) => l === step.heat || t.includes(`до ${HEAT_GEN[l]} `) || t.includes(`на ${HEAT_PREP[l]} огне`));
  const knob = KNOB[stove] || KNOB.electric;
  return levels.map((l) => `${l} огонь (${MEDIUM_RU[med]}) — ${knob[l]}; ${SIGN[med][l]}`);
}
